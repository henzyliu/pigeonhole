const ServerName = "local"

var ErrDirectMediaUnsupported = errors.New("direct media is not supported by the local homeserver")

// Connector implements bridgev2.MatrixConnector for a single network bridge.
// All connectors share one Store, so the UI sees a single unified inbox.
type Connector struct {
	Store   *Store
	Network string
	Bridge  *bridgev2.Bridge

	// OnBridgeState receives login connection state changes (connected,
	// bad credentials, ...).
	OnBridgeState func(network string, state status.BridgeState)

	bot *Intent
}

var _ bridgev2.MatrixConnector = (*Connector)(nil)

func NewConnector(store *Store, network string) *Connector {
	c := &Connector{Store: store, Network: network}
	c.bot = &Intent{c: c, mxid: id.NewUserID(network+"bot", ServerName)}
	return c
}

func (c *Connector) Init(br *bridgev2.Bridge)        { c.Bridge = br }
func (c *Connector) Start(ctx context.Context) error { return nil }
func (c *Connector) PreStop()                        {}
func (c *Connector) Stop()                           {}
func (c *Connector) ServerName() string              { return ServerName }

func (c *Connector) GetCapabilities() *bridgev2.MatrixCapabilities {
	return &bridgev2.MatrixCapabilities{
		AutoJoinInvites:       true,
		BatchSending:          true,
		ArbitraryMemberChange: true,
	}
}

func (c *Connector) ghostPrefix() string { return "@" + c.Network + "_" }

func (c *Connector) FormatGhostMXID(userID networkid.UserID) id.UserID {
	return id.UserID(c.ghostPrefix() + id.EncodeUserLocalpart(string(userID)) + ":" + ServerName)
}

func (c *Connector) ParseGhostMXID(userID id.UserID) (networkid.UserID, bool) {
	localpart, server, err := userID.Parse()
	prefix := strings.TrimPrefix(c.ghostPrefix(), "@")
	if err != nil || server != ServerName || !strings.HasPrefix(localpart, prefix) {
		return "", false
	}
	decoded, err := id.DecodeUserLocalpart(strings.TrimPrefix(localpart, prefix))
	if err != nil {
		return "", false
	}
	return networkid.UserID(decoded), true
}

func (c *Connector) GhostIntent(userID networkid.UserID) bridgev2.MatrixAPI {
	return &Intent{c: c, mxid: c.FormatGhostMXID(userID)}
}

// NewUserIntent is how bridgev2 gets a double puppet for the local user, which
// lets messages you send from your phone show up as "you" in the inbox.
func (c *Connector) NewUserIntent(ctx context.Context, userID id.UserID, accessToken string) (bridgev2.MatrixAPI, string, error) {
	if accessToken == "" {
		accessToken = "local"
	}
	return &Intent{c: c, mxid: userID}, accessToken, nil
}

func (c *Connector) BotIntent() bridgev2.MatrixAPI { return c.bot }

func (c *Connector) SendBridgeStatus(ctx context.Context, state *status.BridgeState) error {
	if c.OnBridgeState != nil {
		c.OnBridgeState(c.Network, *state)
	}
	return nil
}

func (c *Connector) SendMessageStatus(ctx context.Context, st *bridgev2.MessageStatus, evt *bridgev2.MessageStatusEventInfo) {
	if evt == nil || evt.SourceEventID == "" {
		return
	}
	c.Store.SetEventStatus(ctx, evt.SourceEventID, evt.RoomID, strings.ToLower(string(st.Status)))
}

func (c *Connector) GenerateContentURI(ctx context.Context, mediaID networkid.MediaID) (id.ContentURIString, error) {
	return "", ErrDirectMediaUnsupported
}

func (c *Connector) ParseContentURI(ctx context.Context, contentURI id.ContentURIString) (networkid.MediaID, error) {
	return nil, ErrDirectMediaUnsupported
}

func (c *Connector) GetPowerLevels(ctx context.Context, roomID id.RoomID) (*event.PowerLevelsEventContent, error) {
	return &event.PowerLevelsEventContent{
		Users: map[id.UserID]int{c.bot.mxid: 100, c.Store.Me: 100},
	}, nil
}

func (c *Connector) GetMembers(ctx context.Context, roomID id.RoomID) (map[id.UserID]*event.MemberEventContent, error) {
	members, err := c.Store.Members(ctx, roomID)
	if err != nil {
		return nil, err
	}
	out := make(map[id.UserID]*event.MemberEventContent, len(members))
	for userID, membership := range members {
		out[userID] = &event.MemberEventContent{Membership: membership}
	}
	return out, nil
}

func (c *Connector) GetMemberInfo(ctx context.Context, roomID id.RoomID, userID id.UserID) (*event.MemberEventContent, error) {
	members, err := c.Store.Members(ctx, roomID)
	if err != nil {
		return nil, err
	}
	membership, ok := members[userID]
	if !ok {
		membership = event.MembershipLeave
	}
	return &event.MemberEventContent{Membership: membership}, nil
}

// BatchSend stores backfilled history. Event IDs are pre-generated by the
// bridge (see GenerateDeterministicEventID) so replies and reactions line up.
func (c *Connector) BatchSend(ctx context.Context, roomID id.RoomID, req *mautrix.ReqBeeperBatchSend, extras []*bridgev2.MatrixSendExtra) (*mautrix.RespBeeperBatchSend, error) {
	countUnread := req.Forward && req.SendNotification && req.MarkReadBy == ""
	resp := &mautrix.RespBeeperBatchSend{EventIDs: make([]id.EventID, len(req.Events))}
	for i, evt := range req.Events {
		if evt.ID == "" {
			evt.ID = newEventID()
		}
		evt.RoomID = roomID
		if err := c.Store.HandleEvent(ctx, evt, countUnread); err != nil {
			return nil, err
		}
		resp.EventIDs[i] = evt.ID
	}
	if req.Forward && req.MarkReadBy != "" {
		_ = c.Store.MarkRead(ctx, roomID)
	}
	return resp, nil
}

func (c *Connector) GenerateDeterministicRoomID(key networkid.PortalKey) id.RoomID {
	return id.RoomID("!" + hashID(c.Network, string(key.ID), string(key.Receiver)) + ":" + ServerName)
}

func (c *Connector) GenerateDeterministicEventID(roomID id.RoomID, _ networkid.PortalKey, messageID networkid.MessageID, partID networkid.PartID) id.EventID {
	return id.EventID("$" + hashID(string(roomID), string(messageID), string(partID)) + ":" + ServerName)
}

func (c *Connector) GenerateReactionEventID(roomID id.RoomID, targetMessage *database.Message, sender networkid.UserID, emojiID networkid.EmojiID) id.EventID {
	return id.EventID("$" + hashID(string(roomID), string(targetMessage.ID), string(targetMessage.PartID), string(sender), string(emojiID)) + ":" + ServerName)
}

func hashID(parts ...string) string {
	h := sha256.New()
	for _, part := range parts {
		h.Write([]byte(part))
		h.Write([]byte{0})
	}
	return base64.RawURLEncoding.EncodeToString(h.Sum(nil))
}

func randomID() string {
	b := make([]byte, 18)
	_, _ = rand.Read(b)
	return base64.RawURLEncoding.EncodeToString(b)
}

func newEventID() id.EventID { return id.EventID("$" + randomID() + ":" + ServerName) }

// NewEventID generates an ID for an event originating in the local UI.
func NewEventID() id.EventID { return newEventID() }
